# The per-stage oracle fixtures (test-data/fixtures/ and test-data/fixtures-local/).
"""Writes the per-stage reference tensors the Rust port is tested against, for every clip in
test-data/clips/, into test-data/fixtures/<clip>/ (one .npy per tensor, plus manifest.json).

The model is upstream's own JAX code (needle-reference, pinned in REFERENCE) running on the
weights rebuilt from models/whistle.cact (cact_params.py), in deployment numerics: activations
A8 and the KV path at the archive's kv_bits (`quantize.configure_deploy`), `quant=True`.

Decoding follows upstream's greedy reference (`whistle_finetune._score_quantised`): BOS, then a
language tag (step 0 may only pick a tag, later steps never do), then text until EOS.

Per-layer tensors: flax does not capture inside the `nn.scan` that runs the layer stacks, so each
stack's real inputs are recorded at its call, then every layer is replayed through upstream's
`_LaneBody` on that layer's slice of the parameters, capturing its internals. The replayed
stack's output must match the real one (checked, relative L2; see `replay`), which pins the
replay to the model. Each dumped layer's lanes are exactly `_LaneBody` applied to the previous
dumped layer's lanes, so a Rust layer test should start from the previous layer's fixture.

    oracle/.venv/bin/python -I oracle/dump.py [--full CLIP ...]

`--full` clips (default: FULL below) also get every layer's internals. Only the committed tier
(`committed` below) lives in test-data/fixtures/; the rest goes to the git-ignored
test-data/fixtures-local/. Each manifest lists every array with its tier.
"""
import argparse
import dataclasses
import glob
import json
import os
import shutil
import sys
import wave
from functools import partial

import numpy as np

# `python -I` leaves the script's folder off sys.path.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cact_params as cp  # noqa: E402 (also puts needle-reference on sys.path)

import jax  # noqa: E402
import jax.numpy as jnp  # noqa: E402
import flax.linen as nn  # noqa: E402
from needle.model import quantize  # noqa: E402
from needle.model import whistle as W  # noqa: E402
from needle.model.architecture import ZCRMSNorm  # noqa: E402
from needle.model.export import RefTokenizer, parse_tokenizer_blob, read_export, read_tokenizer_blob  # noqa: E402

ROOT = cp.ROOT
FULL = ("en_samantha", "de_anna")
TOLERANCE = 5e-2


# Committed tier: every clip's stage boundaries and tokens, and for LANE_CLIPS every layer's lane
# state and the logits. Everything else (block internals, the rest) lands in the git-ignored
# test-data/fixtures-local/, regenerated by this script.
LANE_CLIPS = ("en_samantha", "de_anna")
# Whole-layer internals committed for one clip, so each building block (norms, attention, the
# Hadamard MLP, the conv module, Engram at decoder site 3) has a committed input and output.
INTERNALS_CLIP = "en_samantha"
INTERNALS_LAYERS = ("encoder/layer00/", "encoder/layer07/", "decoder/layer00/", "decoder/layer03/")
CORE = ("samples", "features", "stem/out", "encoder/out", "tokens", "decoder/embedded",
        "decoder/memory", "decoder/engram_k", "decoder/engram_v", "decoder/out")


def committed(clip, name):
    if name in CORE:
        return True
    if clip == INTERNALS_CLIP and name.startswith(INTERNALS_LAYERS):
        return True
    if clip in LANE_CLIPS:
        return name == "decoder/logits" or name.endswith("/lanes") or name.endswith("/lanes_in")
    return False


class Fixture:
    def __init__(self, clip, core_root, local_root):
        self.clip = clip
        self.folder = os.path.join(core_root, clip)
        self.local = os.path.join(local_root, clip)
        self.arrays = {}
        for folder in (self.folder, self.local):
            shutil.rmtree(folder, ignore_errors=True)
            os.makedirs(folder)

    def put(self, name, value):
        value = np.asarray(value)
        if value.dtype == np.float64 or value.dtype == jnp.bfloat16:
            value = value.astype(np.float32)
        if value.dtype == np.int64:
            value = value.astype(np.int32)
        if value.dtype == np.bool_:
            value = value.astype(np.uint8)
        value = np.ascontiguousarray(value)
        file = name.replace("/", ".") + ".npy"
        tier = "core" if committed(self.clip, name) else "local"
        np.save(os.path.join(self.folder if tier == "core" else self.local, file), value)
        self.arrays[name] = {"file": file, "tier": tier, "dtype": str(value.dtype), "shape": list(value.shape)}


def read_wav(path):
    with wave.open(path) as w:
        if (w.getnchannels(), w.getsampwidth(), w.getframerate()) != (1, 2, 16000):
            raise ValueError(f"{path} must be 16 kHz mono PCM16")
        return np.frombuffer(w.readframes(w.getnframes()), np.int16).astype(np.float32) / 32768.0


def _stacks(call):
    """Runs `call` with every LaneStack call recorded as (path, args, kwargs, output)."""
    seen = []

    def record(next_fun, args, kwargs, context):
        out = next_fun(*args, **kwargs)
        if isinstance(context.module, W.LaneStack) and context.method_name == "__call__":
            seen.append(("/".join(context.module.path), args, kwargs, out))
        return out

    with nn.intercept_methods(record):
        result = call()
    return result, seen


def _layer_inputs(stack_params, layer, lanes, engram_layers):
    """Layer `layer`'s slice of the stack's mHC parameters and engram site flags, exactly as
    LaneStack.__call__ builds them for the scan (upstream whistle.py, LaneStack)."""
    L = stack_params["mhc_phi_pre"].shape[0]
    lane = np.eye(lanes, dtype=np.float32)[np.arange(L) % lanes]
    hc = {
        "phi_pre": stack_params["mhc_phi_pre"][layer], "phi_post": stack_params["mhc_phi_post"][layer],
        "phi_res": stack_params["mhc_phi_res"][layer], "b_pre": stack_params["mhc_b_pre"][layer],
        "b_post": stack_params["mhc_b_post"][layer], "b_res": stack_params["mhc_b_res"][layer],
        "a_pre": stack_params["mhc_a_pre"][layer], "a_post": stack_params["mhc_a_post"][layer],
        "a_res": stack_params["mhc_a_res"][layer],
        "pre_off": jnp.asarray(8 * lane[layer] - 4), "post_off": jnp.asarray(-4 * (1 - lane[layer])),
    }
    flags = None
    if engram_layers:
        flags = np.zeros((L, len(engram_layers)), np.float32)
        for s, site in enumerate(engram_layers):
            flags[site, s] = 1.0
        flags = jnp.asarray(flags[layer])
    block = jax.tree_util.tree_map(lambda a: a[layer], stack_params["layers"]["block"])
    return block, (flags, hc)


def replay(fixture, prefix, stack_params, recorded, make, lanes, engram_layers, internals):
    """Replays one recorded LaneStack layer by layer; stores each layer's lane state (and with
    `internals`, everything flax captures inside the block) and checks the final output."""
    _path, args, kwargs, real = recorded
    x = jnp.asarray(args[0], jnp.float32)
    quant = kwargs.get("quant", args[1] if len(args) > 1 else False)
    block_kwargs = {k: v for k, v in kwargs.items() if k != "quant"}
    x = jnp.broadcast_to(x[:, :, None, :], (*x.shape[:2], lanes, x.shape[-1]))
    fixture.put(f"{prefix}/lanes_in", x[0])
    body = W._LaneBody(make, jnp.float32)
    for layer in range(stack_params["mhc_phi_pre"].shape[0]):
        block, xs = _layer_inputs(stack_params, layer, lanes, engram_layers)
        block_in = []

        def record_block_input(next_fun, args, kwargs, context):
            # The block's input is the lanes' pre-mix, which flax does not capture.
            if context.module.name == "block" and context.method_name == "__call__":
                block_in.append(args[0])
            return next_fun(*args, **kwargs)

        with nn.intercept_methods(record_block_input):
            result = body.apply({"params": {"block": block}}, x, xs, quant, block_kwargs,
                                capture_intermediates=internals)
        (x, _), state = result if internals else (result, None)
        fixture.put(f"{prefix}/layer{layer:02d}/lanes", x[0])
        if internals:
            fixture.put(f"{prefix}/layer{layer:02d}/block_in", block_in[0][0])
            for path, value in jax.tree_util.tree_flatten_with_path(state["intermediates"])[0]:
                keys = [getattr(k, "key", getattr(k, "idx", None)) for k in path]
                name = "/".join(str(k) for k in keys if k != "__call__")
                fixture.put(f"{prefix}/layer{layer:02d}/{name}", value[0])
    norm = ZCRMSNorm(dtype=jnp.float32)
    out = norm.apply({"params": {"scale": stack_params["final_norm"]["scale"]}}, jnp.mean(x, axis=2))
    # A8 fake quantization is discontinuous: the scan's compiled body and the eager replay
    # round a few activations to neighbouring int8 steps, and those flips spread through the
    # stack. Upstream alone shows the same spread: its encoder output moves 1.5-2.3% (relative
    # L2) between jit and eager, or between scan unroll settings (measured 2026-10-24, jax
    # 0.12.0.1). Without quantization replay and stack agree to ~2e-6, so the bound below still
    # catches a wrong replay (a misplaced slice or flag is off by O(1)).
    err = float(jnp.linalg.norm(out - real) / jnp.linalg.norm(real))
    if err > TOLERANCE:
        raise AssertionError(f"{prefix}: layer-by-layer replay is {err:.3g} (relative L2) from the real stack")
    return err


def greedy(model, params, cfg, enc, frames):
    """Upstream's greedy reference decode for one clip (whistle_finetune._score_quantised)."""
    step = jax.jit(lambda p, tokens, e, f: model.apply({"params": p}, tokens, e, f, True,
                                                       method=W.Whistle.logits))
    tags = np.arange(cfg.vocab) >= cfg.text
    tokens = np.full((1, cfg.max_tokens), cfg.pad, np.int32)
    tokens[:, 0] = cfg.bos
    for pos in range(cfg.max_tokens - 1):
        size = min(cfg.max_tokens, (pos // 64 + 1) * 64)
        logits = np.array(step(params, tokens[:, :size], enc, frames)[:, pos])
        logits[:, tags != (pos == 0)] = -np.inf
        pick = int(logits.argmax(-1)[0])
        tokens[0, pos + 1] = pick
        if pick == cfg.eos:
            return tokens[0, :pos + 2]
    return tokens[0]


def dump_clip(name, samples, model, params, cfg, tokenizer, internals, out_root, local_root):
    fixture = Fixture(name, out_root, local_root)
    wav, lengths = jnp.asarray(samples[None]), jnp.asarray([len(samples)], jnp.int32)
    fixture.put("samples", samples)

    features, feature_frames = W.features(cfg, wav, lengths)
    fixture.put("features", features[0])

    def encode():
        return model.apply({"params": params}, wav, lengths, True, method=W.Whistle.encode,
                           capture_intermediates=True)

    ((enc, frames), state), stacks = _stacks(encode)
    stem = state["intermediates"]["stem"]
    fixture.put("stem/out", stem["__call__"][0][0][0])
    for key in sorted(k for k in stem if k != "__call__" and k != "out"):
        fixture.put(f"stem/{key}", stem[key]["__call__"][0][0])
    fixture.put("encoder/out", enc[0])
    errors = {"encoder": replay(fixture, "encoder", params["encoder"], stacks[0],
                                partial(W.EncoderBlock, cfg, jnp.float32), cfg.enc_lanes, (), internals)}

    tokens = greedy(model, params, cfg, enc, frames)
    fixture.put("tokens", tokens)

    def decode():
        return model.apply({"params": params}, jnp.asarray(tokens[None]), enc, frames, True,
                           method=W.Whistle.logits)

    logits, stacks = _stacks(decode)
    fixture.put("decoder/logits", logits[0])
    _path, args, kwargs, real = stacks[0]
    fixture.put("decoder/embedded", args[0][0])
    fixture.put("decoder/memory", kwargs["mem"][0])
    fixture.put("decoder/engram_k", kwargs["engram_kv"][0][:, 0])
    fixture.put("decoder/engram_v", kwargs["engram_kv"][1][:, 0])
    fixture.put("decoder/out", real[0])
    errors["decoder"] = replay(fixture, "decoder", params["stack"], stacks[0],
                               partial(W.DecoderBlock, cfg, jnp.float32), cfg.lanes, cfg.sites, internals)

    text_ids = [int(t) for t in tokens[2:] if t != cfg.eos]
    language = cfg.languages[int(tokens[1]) - cfg.text] if tokens[1] >= cfg.text else ""
    manifest = {
        "clip": name,
        "samples": len(samples),
        "feature_frames": int(feature_frames[0]),
        "encoder_frames": int(frames[0]),
        "language": language,
        "tokens": [int(t) for t in tokens],
        "text": tokenizer.decode(text_ids),
        "replay_max_abs_error": errors,
        "internals": internals,
        "arrays": fixture.arrays,
    }
    with open(os.path.join(fixture.folder, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=1)
        f.write("\n")
    return manifest


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--full", nargs="*", default=list(FULL))
    args = parser.parse_args()

    cact = os.path.join(ROOT, "models", "whistle.cact")
    params, cfg, *_ = cp.load(cact, os.path.join(ROOT, "models", "whistle.safetensors"))
    # remat only trades memory for recompute in training; the replay needs plain modules.
    cfg = dataclasses.replace(cfg, remat=False)
    meta, _ = read_export(cact)
    quantize.configure_deploy(act_bits=8, kv_bits=meta["kv_bits"], kv_group=64)
    tokenizer = RefTokenizer(parse_tokenizer_blob(read_tokenizer_blob(cact)))
    model = W.Whistle(cfg)

    out_root = os.path.join(ROOT, "test-data", "fixtures")
    local_root = os.path.join(ROOT, "test-data", "fixtures-local")
    index = {"reference": open(os.path.join(ROOT, "REFERENCE")).read().split("\n"),
             "deploy": {"act_bits": 8, "kv_bits": meta["kv_bits"], "kv_group": 64},
             "jax": jax.__version__, "clips": []}
    for path in sorted(glob.glob(os.path.join(ROOT, "test-data", "clips", "*.wav"))):
        name = os.path.splitext(os.path.basename(path))[0]
        m = dump_clip(name, read_wav(path), model, params, cfg, tokenizer, name in args.full, out_root, local_root)
        index["clips"].append(name)
        print(f"{name:12} {m['language'] or '--':3} {m['text']}   replay {m['replay_max_abs_error']}")
    index["reference"] = [line for line in index["reference"] if line]
    with open(os.path.join(out_root, "index.json"), "w", encoding="utf-8") as f:
        json.dump(index, f, indent=1)
        f.write("\n")


if __name__ == "__main__":
    main()
