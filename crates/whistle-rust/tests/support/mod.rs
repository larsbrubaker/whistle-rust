// Shared test support for whistle-rust's test areas: the oracle fixtures (test-data/fixtures/,
// written by oracle/dump.py), their .npy reader (`npy`) and the comparison every stage test uses
// (`relative_l2`, CLAUDE.md "Tolerance policy"). Each area binary pulls it in with
// `#[path = "support/mod.rs"] mod support;`.

#![allow(dead_code)] // each area binary uses its own subset

pub mod npy;

use std::path::{Path, PathBuf};

use serde_json::Value;

pub use npy::Npy;

pub fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("crates/whistle-rust sits two levels below the workspace root")
        .to_path_buf()
}

/// The model archive, fetched by scripts/fetch-weights.sh (git-ignored, 16.9 MB).
pub fn model_path() -> PathBuf {
    repo_root().join("models").join("whistle.cact")
}

fn read_json(path: &Path) -> Value {
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

/// test-data/fixtures/index.json: the clips, the pinned reference and the deploy numerics.
pub fn index() -> Value {
    read_json(&repo_root().join("test-data/fixtures/index.json"))
}

pub fn clip_names() -> Vec<String> {
    index()["clips"]
        .as_array()
        .expect("index.json lists clips")
        .iter()
        .map(|c| c.as_str().expect("clip name").to_string())
        .collect()
}

/// One clip's fixture: its manifest and the arrays it lists.
pub struct Fixture {
    pub clip: String,
    pub manifest: Value,
}

impl Fixture {
    pub fn load(clip: &str) -> Fixture {
        let manifest = read_json(
            &repo_root()
                .join("test-data/fixtures")
                .join(clip)
                .join("manifest.json"),
        );
        Fixture {
            clip: clip.to_string(),
            manifest,
        }
    }

    /// Every array name the manifest lists, in its order.
    pub fn names(&self) -> Vec<String> {
        self.entries().keys().cloned().collect()
    }

    fn entries(&self) -> &serde_json::Map<String, Value> {
        self.manifest["arrays"]
            .as_object()
            .expect("manifest lists arrays")
    }

    fn entry(&self, name: &str) -> &Value {
        self.entries()
            .get(name)
            .unwrap_or_else(|| panic!("{}: manifest has no array {name}", self.clip))
    }

    /// "core" (committed) or "local" (git-ignored, regenerated by oracle/dump.py).
    pub fn tier(&self, name: &str) -> &str {
        self.entry(name)["tier"].as_str().expect("tier")
    }

    fn path(&self, name: &str) -> PathBuf {
        let folder = if self.tier(name) == "core" {
            "fixtures"
        } else {
            "fixtures-local"
        };
        let file = self.entry(name)["file"].as_str().expect("file");
        repo_root()
            .join("test-data")
            .join(folder)
            .join(&self.clip)
            .join(file)
    }

    /// A committed array. Panics if it is missing: the committed tier is the contract.
    pub fn array(&self, name: &str) -> Npy {
        assert_eq!(
            self.tier(name),
            "core",
            "{}: {name} is not committed; use local_array",
            self.clip
        );
        npy::read(&self.path(name)).unwrap_or_else(|e| panic!("{}: {e}", self.clip))
    }

    /// A local-tier array, or None when test-data/fixtures-local/ has not been generated
    /// (`oracle/dump.py`). For debugging aids only; the contract tests use `array`.
    pub fn local_array(&self, name: &str) -> Option<Npy> {
        let path = self.path(name);
        path.is_file()
            .then(|| npy::read(&path).unwrap_or_else(|e| panic!("{}: {e}", self.clip)))
    }

    pub fn f32(&self, name: &str) -> (Vec<usize>, Vec<f32>) {
        match self.array(name) {
            Npy::F32 { shape, data } => (shape, data),
            other => panic!("{}: {name} is {}, not float32", self.clip, other.dtype()),
        }
    }

    /// The greedy reference decode: BOS, language tag, text tokens, EOS.
    pub fn tokens(&self) -> Vec<u32> {
        self.manifest["tokens"]
            .as_array()
            .expect("tokens")
            .iter()
            .map(|t| t.as_u64().expect("token id") as u32)
            .collect()
    }

    pub fn text(&self) -> &str {
        self.manifest["text"].as_str().expect("text")
    }

    pub fn language(&self) -> &str {
        self.manifest["language"].as_str().expect("language")
    }
}

/// ||actual - expected|| / ||expected|| over all elements (CLAUDE.md "Tolerance policy").
/// An all-zero reference compares by the absolute norm of `actual` instead.
pub fn relative_l2(actual: &[f32], expected: &[f32]) -> f64 {
    assert_eq!(
        actual.len(),
        expected.len(),
        "compared arrays differ in length"
    );
    let (mut diff, mut norm) = (0.0f64, 0.0f64);
    for (&a, &e) in actual.iter().zip(expected) {
        let d = f64::from(a) - f64::from(e);
        diff += d * d;
        norm += f64::from(e) * f64::from(e);
    }
    if norm == 0.0 {
        diff.sqrt()
    } else {
        (diff / norm).sqrt()
    }
}
